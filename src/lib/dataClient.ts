const META = metaStaticJson as MetaStaticShape;

export async function loadMeta(): Promise<DataMeta> {
  return {
    unitsUpdatedAt: META.unitsUpdatedAt,
    incentivesUpdatedAt: META.incentivesUpdatedAt,
    dealersUpdatedAt: META.dealersUpdatedAt,
    snapshotCount: META.snapshotCount,
    lastSnapshotAt: META.lastSnapshotAt,
  };
}

export async function listSnapshotFiles(): Promise<string[]> {
  return [...META.snapshotFiles];
}

export async function loadSnapshots(limit?: number): Promise<Snapshot[]> {
  const all = z.array(SnapshotSchema).parse(META.snapshots);
  return limit ? all.slice(-limit) : all;
}

// ----- consolidated dataset (mirrors data.ts:loadScoredUnits) -----

export async function loadScoredUnits(
  buyerContextOrProvince?: import("./types").BuyerContext | import("./constants").Province,
): Promise<{
  units: ScoredUnit[];
  dealers: Dealer[];
  dealerById: Map<string, Dealer>;
  incentives: Incentive[];
  buyerContext: import("./types").BuyerContext | null;
  buyerProvince: import("./constants").Province | null;
}> {
  const buyerContext: import("./types").BuyerContext | undefined =
    typeof buyerContextOrProvince === "string"
      ? { province: buyerContextOrProvince, loyalty: false, conquest: false }
      : buyerContextOrProvince;

  const [units, dealers, incentives] = await Promise.all([
    loadUnits(),
    loadDealers(),
    loadIncentives(),
  ]);
  const dealerById = new Map(dealers.map((d) => [d.id, d]));
  const unitsByDealer = new Map<string, InventoryUnit[]>();
  for (const u of units) {
    const arr = unitsByDealer.get(u.dealerId) ?? [];
    arr.push(u);
    unitsByDealer.set(u.dealerId, arr);
  }

  const scored = units.map((unit) => {
    const dealer = dealerById.get(unit.dealerId);
    if (!dealer) {
      throw new Error(`Unit ${unit.id} references unknown dealer ${unit.dealerId}`);
    }
    const applicable = applicableIncentives(unit, dealer, incentives, buyerContext);
    const otdBreakdown = computeOtd(unit, dealer, applicable, buyerContext?.province);
    const finance = computeFinanceOtd(unit, dealer, applicable, buyerContext);
    const lease = computeLeaseOtd(unit, dealer, applicable, buyerContext);
    const { score, breakdown } = computeDealScore({
      unit,
      dealer,
      dealerUnits: unitsByDealer.get(dealer.id) ?? [],
      applicable,
    });
    return {
      ...unit,
      otdCad: otdBreakdown.total,
      otdBreakdown,
      otdPaths: {
        cash: otdBreakdown,
        ...(finance ? { finance } : {}),
        ...(lease ? { lease } : {}),
      },
      dealScore: score,
      dealScoreBreakdown: breakdown,
      applicableIncentives: applicable,
    } satisfies ScoredUnit;
  });

  return {
    units: scored,
    dealers,
    dealerById,
    incentives,
    buyerContext: buyerContext ?? null,
    buyerProvince: buyerContext?.province ?? null,
  };
}
