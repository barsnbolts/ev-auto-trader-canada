// ----- single-source loaders (mirror data.ts API surface) -----

export async function loadDealers(): Promise<Dealer[]> {
  const base = z.array(DealerSchema).parse(dealersJson);
  // Backfill dealer phone + address from per-listing enrichment when
  // dealers.json still has placeholder values. Same logic as data.ts.
  const enrichment = enrichmentJson as Record<string, { phone?: string; streetAddress?: string }>;
  const unitsRaw = unitsJson as Array<{ id: string; dealerId: string }>;
  const dealerEnrich = new Map<string, { phone?: string; streetAddress?: string }>();
  for (const u of unitsRaw) {
    const e = enrichment[u.id];
    if (!e) continue;
    if (!dealerEnrich.has(u.dealerId)) dealerEnrich.set(u.dealerId, e);
  }
  return base.map((d) => {
    const e = dealerEnrich.get(d.id);
    if (!e) return d;
    const phone = !d.phone && e.phone ? e.phone : d.phone;
    const address =
      (!d.address || d.address === "Address not yet captured") && e.streetAddress
        ? e.streetAddress
        : d.address;
    return { ...d, phone, address };
  });
}

export async function loadUnits(): Promise<InventoryUnit[]> {
  const base = z.array(InventoryUnitSchema).parse(unitsJson);
  const enrichment = enrichmentJson as Record<string, Partial<InventoryUnit>>;
  return base.map((u) => {
    const e = enrichment[u.id];
    if (!e) return u;
    return {
      ...u,
      daysOnLot: e.daysOnLot ?? u.daysOnLot,
      vin: e.vin ?? u.vin,
      msrp: e.msrp ?? u.msrp,
      exteriorColor: e.exteriorColor ?? u.exteriorColor,
      interiorColor: e.interiorColor ?? u.interiorColor,
    };
  });
}

